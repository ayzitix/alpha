#!/usr/bin/env bun

// Regenerates docs/EXPORTS.md: every export in the packages a contributor is
// most likely to edit, with its doc comment or, when there is none, its
// declaration line.
import { readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const targets = ["packages/cli/src", "packages/tui/src/mini"]
const out = path.join(root, "docs/EXPORTS.md")

const kinds: Record<string, string> = {
  function: "fn",
  "function*": "gen",
  const: "const",
  class: "class",
  namespace: "ns",
  type: "type",
  interface: "iface",
  enum: "enum",
}

const declaration =
  /^export\s+(?:default\s+)?(?:async\s+)?(function\*?|const|class|namespace|type|interface|enum)\s+([A-Za-z0-9_$]+)(.*)$/gm

function doc(lines: string[], index: number): string {
  let i = index - 1
  while (i >= 0 && lines[i]!.trim() === "") i--
  const collected: string[] = []
  if (i >= 0 && lines[i]!.trim().endsWith("*/")) {
    while (i >= 0) {
      collected.push(lines[i]!.trim())
      if (lines[i]!.trim().startsWith("/*")) break
      i--
    }
    return collected
      .reverse()
      .join(" ")
      .replace(/^\/\*+/, "")
      .replace(/\*\/$/, "")
      .replace(/(^|\s)\*\s?/g, "$1")
      .replace(/\s+/g, " ")
      .trim()
  }
  while (i >= 0 && lines[i]!.trim().startsWith("//")) {
    collected.push(lines[i]!.trim().replace(/^\/+/, "").trim())
    i--
  }
  return collected.reverse().join(" ").replace(/\s+/g, " ").trim()
}

function signature(line: string): string {
  return line.replace(/\s+/g, " ").trim().replace(/\{$/, "").trim().slice(0, 110)
}

async function files(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  const found = await Promise.all(
    entries.map(async (entry) => {
      const next = path.join(dir, entry.name)
      if (entry.isDirectory()) return files(next)
      if (!entry.name.endsWith(".ts") && !entry.name.endsWith(".tsx")) return []
      if (entry.name.includes(".test.") || entry.name.endsWith(".d.ts")) return []
      return [next]
    }),
  )
  return found.flat().sort()
}

const sections: string[] = []

for (const target of targets) {
  for (const file of await files(path.join(root, target))) {
    const source = await readFile(file, "utf8")
    const lines = source.split("\n")
    const items: string[] = []
    for (const match of source.matchAll(declaration)) {
      const kind = kinds[match[1]!]
      const name = match[2]!
      const index = source.slice(0, match.index).split("\n").length - 1
      const text = doc(lines, index)
      const tail = text ? ` — ${text}` : ` — \`${signature(match[0])}\``
      items.push(`- **${name}** \`${kind}\`${tail}`)
    }
    if (!items.length) continue
    sections.push(`## \`${path.relative(root, file).replace(/^packages\//, "")}\`\n\n${items.join("\n")}`)
  }
}

const header = [
  "# Export index",
  "",
  "Every exported symbol in `packages/cli` and `packages/tui/src/mini`, with its",
  "documentation comment when the source has one, otherwise its declaration.",
  "",
  "Generated by `bun run script/gen-exports.ts` — re-run it after large refactors.",
  "",
].join("\n")

await writeFile(out, `${header}\n${sections.join("\n\n")}\n`)
console.log(`wrote ${path.relative(root, out)} (${sections.length} files)`)
